"""Builds scripts/pcg/QuranData.gd and scripts/pcg/CountryData.gd from two MIT-licensed
npm packages (downloaded with `npm pack`, never executed):
  quran-meta 7.0.0      (Hafs riwaya: surah ayah counts, juz starts, Arabic names)
  world-countries 5.1.0 (UN member states: capital, region, area, borders, Urdu names)
Usage: python3 -I make_question_data.py QURAN_META_DIST WORLD_COUNTRIES_DIR OUT_DIR
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

dist, wc, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])


def js_array(text: str, name: str) -> list:
    start = text.index(name + ":")
    i = text.index("[", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "[":
            depth += 1
        elif text[j] == "]":
            depth -= 1
            if depth == 0:
                body = text[i:j + 1]
                break
    body = re.sub(r",(\s*[\]}])", r"\1", body)
    return json.loads(body.replace("false", "false").replace("true", "true"))


hafs = next(dist.glob("HafsLists-*.js")).read_text(encoding="utf-8")
surahs = js_array(hafs, "SurahList")[1:115]       # [start, ayahs, rev_order, rukus, arabic, meccan]
juz_starts = js_array(hafs, "JuzList")[1:31]      # global ayah index of juz 1..30
ur_file = next(dist.glob("surah.ur-*.js")).read_text(encoding="utf-8")
names = re.findall(r'\["([^"]+)",\s*"[^"]*"\]', ur_file)   # transliterations, 1..114

assert len(surahs) == 114 and len(names) == 114 and len(juz_starts) == 30
total = sum(s[1] for s in surahs)
assert total == 6236, total


def strip_marks(s: str) -> str:
    return "".join(ch for ch in s if unicodedata.category(ch) != "Mn")


def juz_of(global_start: int) -> int:
    j = 1
    for k, start in enumerate(juz_starts):
        if start <= global_start:
            j = k + 1
    return j


rows = []
for i, s in enumerate(surahs):
    rows.append([names[i], strip_marks(s[4]).strip(), s[1], juz_of(s[0])])

# Well-known facts used as checks (any Pakistani mushaf, Hafs 'an 'Asim).
checks = {1: (7, 1), 2: (286, 1), 3: (200, 3), 18: (110, 15), 36: (83, 22), 55: (78, 27),
          67: (30, 29), 78: (40, 30), 108: (3, 30), 112: (4, 30), 114: (6, 30)}
for num, (ayahs, juz) in checks.items():
    assert rows[num - 1][2] == ayahs and rows[num - 1][3] == juz, (num, rows[num - 1])

lines = ["extends RefCounted", "## GENERATED by tools/make_question_data.py from quran-meta 7.0.0 (MIT), Hafs riwaya.",
         "## Each row: [English transliteration, Arabic name, ayah count, juz (para) where it begins].",
         "## Checked: 114 surahs, 6236 ayahs, and known values (Al-Baqarah 286, Yasin 83 in para 22, ...).", "",
         "const SURAHS := ["]
for r in rows:
    lines.append("\t" + json.dumps(r, ensure_ascii=False) + ",")
lines += ["]", ""]
(out / "QuranData.gd").write_text("\n".join(lines), encoding="utf-8")

countries = json.loads((wc / "countries.json").read_text(encoding="utf-8"))
EXCLUDE = {"ISR"}                       # not recognised by Pakistan; kept out of the game
TRANSCONTINENTAL = {"RUS", "TUR", "KAZ", "AZE", "GEO", "ARM", "CYP", "EGY"}
keep = [c for c in countries if c.get("unMember") and c["cca3"] not in EXCLUDE]
codes = {c["cca3"] for c in keep}
crow = []
for c in sorted(keep, key=lambda c: c["name"]["common"]):
    ur = c["translations"].get("urd", {}).get("common", c["name"]["common"])
    caps = c.get("capital", [])
    crow.append([
        c["cca3"], c["name"]["common"], ur,
        caps[0] if len(caps) == 1 else "",
        "" if c["cca3"] in TRANSCONTINENTAL else c["region"],
        int(round(c["area"])), bool(c.get("landlocked")),
        [b for b in c.get("borders", []) if b in codes],
    ])
# Keep only land borders that BOTH countries list (drops e.g. Sri Lanka -> India).
by_code = {r[0]: r for r in crow}
for r in crow:
    r[7] = [b for b in r[7] if r[0] in by_code[b][7]]
pak = [r for r in crow if r[0] == "PAK"][0]
assert pak[3] == "Islamabad" and set(pak[7]) == {"AFG", "CHN", "IND", "IRN"}, pak
lines = ["extends RefCounted", "## GENERATED by tools/make_question_data.py from world-countries 5.1.0 (ODbL data, MIT code).",
         "## UN member states (Israel excluded). Row: [code, English, Urdu, capital ('' if several),",
         "## region ('' if transcontinental), area km2, landlocked, neighbour codes].", "",
         "const COUNTRIES := ["]
for r in crow:
    lines.append("\t" + json.dumps(r, ensure_ascii=False) + ",")
lines += ["]", ""]
(out / "CountryData.gd").write_text("\n".join(lines), encoding="utf-8")
print("surahs", len(rows), "ayahs", total, "countries", len(crow))
